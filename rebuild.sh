#!/bin/bash
# ==========================================
# Скрипт пересборки и обновления FileShare
# ==========================================
# Используется после внесения изменений в код
# для обновления Docker образов и перезапуска
# ==========================================

set -e

echo "╔══════════════════════════════════════════════════════════╗"
echo "║                                                          ║"
echo "║   🔄 Пересборка и обновление FileShare                   ║"
echo "║                                                          ║"
echo "╚══════════════════════════════════════════════════════════╝"
echo ""

# Переход в директорию проекта
# Поддерживает как production установку (/opt/fileshare), так и разработку (любая директория)
if [ -d "/opt/fileshare" ] && [ -f "/opt/fileshare/docker-compose.yml" ]; then
    cd "/opt/fileshare"
else
    cd "$(dirname "$0")"
fi

# Остановка контейнеров
echo "🛑 Остановка контейнеров..."
docker compose down
echo "✅ Контейнеры остановлены"
echo ""

# Пересборка образов
echo "🔨 Пересборка Docker образов..."
docker compose build --no-cache
echo "✅ Образы пересобраны"
echo ""

# Запуск контейнеров
echo "🚀 Запуск контейнеров..."
docker compose up -d
echo "✅ Контейнеры запущены"
echo ""

# Ожидание готовности сервисов
echo "⏳ Ожидание готовности сервисов..."
sleep 10

# Проверка здоровья backend
echo "🔍 Проверка здоровья backend..."
if curl -f http://localhost:3001/api/health > /dev/null 2>&1; then
    echo "✅ Backend работает"
else
    echo "⚠️  Backend не отвечает (это нормально, если он ещё запускается)"
fi
echo ""

# Проверка здоровья frontend
echo "🔍 Проверка здоровья frontend..."
if curl -f http://localhost:80 > /dev/null 2>&1; then
    echo "✅ Frontend работает"
else
    echo "⚠️  Frontend не отвечает (это нормально, если он ещё запускается)"
fi
echo ""

echo "╔══════════════════════════════════════════════════════════╗"
echo "║                                                          ║"
echo "║   ✅ Обновление завершено!                               ║"
echo "║                                                          ║"
echo "╚══════════════════════════════════════════════════════════╝"
echo ""
echo "📋 Полезные команды:"
echo "   docker compose ps          # Статус контейнеров"
echo "   docker compose logs -f     # Логи в реальном времени"
echo "   docker compose restart     # Перезапуск всех сервисов"
echo ""
